import psycopg
from pgvector.psycopg import register_vector
from psycopg.rows import dict_row
from app.config.settings import DATABASE_URL

def get_connection():
    connection = psycopg.connect(
        DATABASE_URL,
        row_factory=dict_row
    )

    register_vector(connection)

    return connection


def create_tables():
    with get_connection() as conn:
        # Extensão para armazenar e consultar embeddings.
        conn.execute("""
            CREATE EXTENSION IF NOT EXISTS vector
        """)

        # Extensão para busca lexical BM25 (ParadeDB).
        conn.execute("""
            CREATE EXTENSION IF NOT EXISTS pg_search
        """)

        # ENUM dos tipos de chunk.
        conn.execute("""
            DO $$
            BEGIN
                IF NOT EXISTS (
                    SELECT 1
                    FROM pg_type
                    WHERE typname = 'type_doc'
                      AND typnamespace = current_schema()::regnamespace
                ) THEN
                    CREATE TYPE type_doc AS ENUM ('text', 'image');
                END IF;
            END
            $$;
        """)

        # Chats.
        conn.execute("""
            CREATE TABLE IF NOT EXISTS chat (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY
                    PRIMARY KEY
            )
        """)

        # Mensagens dos chats.
        conn.execute("""
            CREATE TABLE IF NOT EXISTS message (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY
                    PRIMARY KEY,
                content TEXT NOT NULL,
                role TEXT NOT NULL
                    CHECK (role IN ('user', 'assistant')),
                sent_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                chat_id BIGINT NOT NULL
                    REFERENCES chat(id)
                    ON DELETE CASCADE
            )
        """)

        # Chunks utilizados no RAG.
        conn.execute("""
            CREATE TABLE IF NOT EXISTS chunks (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY
                    PRIMARY KEY,
                content TEXT NOT NULL,
                document TEXT NOT NULL,
                page INTEGER NOT NULL CHECK (page > 0),
                type type_doc NOT NULL DEFAULT 'text',
                vector_embedding VECTOR(768) NOT NULL
            )
        """)

        # Limpeza da busca textual antiga (tsvector), para bancos já existentes.
        conn.execute("""
            DROP INDEX IF EXISTS idx_chunks_busca_textual
        """)
        conn.execute("""
            ALTER TABLE chunks DROP COLUMN IF EXISTS busca_textual
        """)

        # Índice para carregar mensagens de um chat em ordem.
        conn.execute("""
            CREATE INDEX IF NOT EXISTS idx_message_chat_sent
            ON message (chat_id, sent_at, id)
        """)

        # Índice lexical BM25 (apenas um índice BM25 por tabela;
        # key_field precisa ser único).
        conn.execute("""
            CREATE INDEX IF NOT EXISTS idx_chunks_bm25
            ON chunks USING bm25 (
                id,
                (content::pdb.simple('stemmer=portuguese'))
            )
            WITH (key_field = 'id')
        """)

        # Índice vetorial aproximado.
        conn.execute("""
            CREATE INDEX IF NOT EXISTS idx_chunks_embedding
            ON chunks USING HNSW (
                vector_embedding vector_cosine_ops
            )
        """)

create_tables()